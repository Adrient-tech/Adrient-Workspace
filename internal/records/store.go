// Role levels.
const (
	RoleNone  = 0
	RoleView  = 1
	RoleEdit  = 2
	RoleAdmin = 3
)

// Limits.
const (
	MaxRecordsPerTable = 500000
	MaxBatch           = 1000
	MaxFieldsPerTable  = 120
	MaxTablesPerBase   = 50
)

// Deps are the other modules' capabilities Records uses. Every one is optional.
type Deps struct {
	Audit knowkit.Audit
	// FileMeta resolves a Drive file the caller may attach.
	FileMeta func(ctx context.Context, org, user, fileID string) (name, mime string, size int64, err error)
	// ExternalRole gives the caller's role (0-3) on bases owned by another module (source "wiki").
	ExternalRole func(ctx context.Context, org, user, source, ref string) int
	// SaveFile stores generated bytes (an export) in the caller's Drive and returns the file id.
	SaveFile func(ctx context.Context, org, user, name, mime string, data []byte) (string, error)
	Now      func() time.Time
}

// Repository is the Postgres store. Every query is org-scoped.
type Repository struct {
	pool    *pgxpool.Pool
	Deps    Deps
	natOnce sync.Once
	natural bool
	// forceMemory makes list() filter and sort in memory (tests compare both paths).
	forceMemory bool
}

// NewRepository constructs a Repository.
func NewRepository(pool *pgxpool.Pool) *Repository { return &Repository{pool: pool} }

// Pool exposes the pool for tests.
func (r *Repository) Pool() *pgxpool.Pool { return r.pool }

func (r *Repository) now() time.Time { return knowkit.Clock(r.Deps.Now) }

func (r *Repository) audit(ctx context.Context, action, typ, id string) {
	if r.Deps.Audit != nil {
		r.Deps.Audit(ctx, action, typ, id)
	}
}

// NewID makes a random uuid (v4).
func NewID() string {
	var b [16]byte
	_, _ = rand.Read(b[:])
	b[6] = b[6]&0x0f | 0x40
	b[8] = b[8]&0x3f | 0x80
	h := hex.EncodeToString(b[:])
	return h[0:8] + "-" + h[8:12] + "-" + h[12:16] + "-" + h[16:20] + "-" + h[20:]
}

// Base is a database of tables.
type Base struct {
	ID          string     `json:"id"`
	Name        string     `json:"name"`
	Description string     `json:"description"`
	Color       string     `json:"color"`
	OwnerID     string     `json:"owner_id"`
	OrgAccess   string     `json:"org_access"`
	Source      string     `json:"source,omitempty"`
	SourceRef   string     `json:"source_ref,omitempty"`
	UpdatedAt   time.Time  `json:"updated_at"`
	TrashedAt   *time.Time `json:"trashed_at,omitempty"`
	Role        int        `json:"role"`
	Tables      []Table    `json:"tables,omitempty"`
	Members     []Member   `json:"members,omitempty"`
}

// Member is a user a base is shared with.
type Member struct {
	UserID string `json:"user_id"`
	Name   string `json:"name,omitempty"`
	Role   string `json:"role"`
}

func roleOfString(s string) int {
	switch s {
	case "viewer":
		return RoleView
	case "editor":
		return RoleEdit
	case "admin":
		return RoleAdmin
	}
	return RoleNone
}

func (r *Repository) roleOn(ctx context.Context, a knowkit.Actor, b *Base) int {
	if b.Source != "" && r.Deps.ExternalRole != nil {
		return r.Deps.ExternalRole(ctx, a.Org, a.User, b.Source, b.SourceRef)
	}
	if b.Source != "" {
		return RoleNone
	}
	if b.OwnerID == a.User || a.Admin {
		return RoleAdmin
	}
	role := RoleNone
	var m string
	_ = r.pool.QueryRow(ctx, `SELECT role FROM adrient.records_base_members WHERE base_id=$1 AND user_id=$2`, b.ID, a.User).Scan(&m)
	role = roleOfString(m)
	switch b.OrgAccess {
	case "view":
		if role < RoleView {
			role = RoleView
		}
	case "edit":
		if role < RoleEdit {
			role = RoleEdit
		}
	}
	return role
}

func (r *Repository) getBase(ctx context.Context, a knowkit.Actor, id string, need int) (*Base, error) {
	if !knowkit.IsUUID(id) {
		return nil, knowkit.ErrNotFound
	}
	b := &Base{ID: id}
	err := r.pool.QueryRow(ctx, `SELECT name, description, color, owner_id::text, org_access, source, source_ref, updated_at, trashed_at
		FROM adrient.records_bases WHERE org_id=$1 AND id=$2`, a.Org, id).
		Scan(&b.Name, &b.Description, &b.Color, &b.OwnerID, &b.OrgAccess, &b.Source, &b.SourceRef, &b.UpdatedAt, &b.TrashedAt)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, knowkit.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	b.Role = r.roleOn(ctx, a, b)
	if b.Role == RoleNone {
		return nil, knowkit.ErrNotFound // do not reveal that it exists
	}
	if b.Role < need {
		return nil, knowkit.ErrForbidden
	}
	if b.TrashedAt != nil && need == RoleEdit {
		return nil, knowkit.Invalid("this base is in the trash; restore it first")
	}
	return b, nil
}

// tableBase resolves a table to its base and checks the role.
func (r *Repository) tableBase(ctx context.Context, a knowkit.Actor, tableID string, need int) (*Base, error) {
	if !knowkit.IsUUID(tableID) {
		return nil, knowkit.ErrNotFound
	}
	var baseID string
	err := r.pool.QueryRow(ctx, `SELECT base_id::text FROM adrient.records_tables WHERE org_id=$1 AND id=$2`, a.Org, tableID).Scan(&baseID)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, knowkit.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return r.getBase(ctx, a, baseID, need)
}

// ListBases lists the bases the caller can open.
func (r *Repository) ListBases(ctx context.Context, a knowkit.Actor, trashed bool) ([]Base, error) {
	q := `SELECT id::text, name, description, color, owner_id::text, org_access, updated_at, trashed_at FROM adrient.records_bases
		WHERE org_id=$1 AND source='' AND (trashed_at IS NOT NULL) = $2 ORDER BY lower(name)`
	rows, err := r.pool.Query(ctx, q, a.Org, trashed)
	if err != nil {
		return nil, err
	}
	var all []Base
	for rows.Next() {
		var b Base
		if err := rows.Scan(&b.ID, &b.Name, &b.Description, &b.Color, &b.OwnerID, &b.OrgAccess, &b.UpdatedAt, &b.TrashedAt); err != nil {
			rows.Close()
			return nil, err
		}
		all = append(all, b)
	}
	rows.Close()
	out := []Base{}
	for _, b := range all {
		b := b
		b.Role = r.roleOn(ctx, a, &b)
		if b.Role > RoleNone && (!trashed || b.Role == RoleAdmin) {
			out = append(out, b)
		}
	}
	return out, nil
}

// BaseInput creates or edits a base.
type BaseInput struct {
	Name        string `json:"name"`
	Description string `json:"description"`
	Color       string `json:"color"`
	OrgAccess   string `json:"org_access"`
	Template    string `json:"template"`
}

func cleanBase(in *BaseInput) error {
	in.Name = strings.TrimSpace(in.Name)
	if in.Name == "" || utf8.RuneCountInString(in.Name) > 120 {
		return knowkit.Invalid("a base needs a name of up to 120 characters")
	}
	if utf8.RuneCountInString(in.Description) > 2000 {
		return knowkit.Invalid("description is too long")
	}
	if in.Color == "" {
		in.Color = "#126C5A"
	}
	if len(in.Color) > 9 || !strings.HasPrefix(in.Color, "#") {
		return knowkit.Invalid("color must look like #126C5A")
	}
	if in.OrgAccess == "" {
		in.OrgAccess = "none"
	}
	if !knowkit.OneOf(in.OrgAccess, "none", "view", "edit") {
		return knowkit.Invalid("org_access must be none, view or edit")
	}
	return nil
}

// CreateBase makes a base, optionally from a template.
func (r *Repository) CreateBase(ctx context.Context, a knowkit.Actor, in BaseInput) (*Base, error) {
	if err := cleanBase(&in); err != nil {
		return nil, err
	}
	var id string
	err := r.pool.QueryRow(ctx, `INSERT INTO adrient.records_bases (org_id, name, description, color, owner_id, org_access) VALUES ($1,$2,$3,$4,$5,$6) RETURNING id::text`,
		a.Org, in.Name, strings.TrimSpace(in.Description), in.Color, a.User, in.OrgAccess).Scan(&id)
	if err != nil {
		return nil, err
	}
	if in.Template == "" || in.Template == "blank" {
		if _, err := r.CreateTable(ctx, a, id, "Table 1"); err != nil {
			return nil, err
		}
	} else if err := r.applyTemplate(ctx, a, id, in.Template); err != nil {
		_, _ = r.pool.Exec(ctx, `DELETE FROM adrient.records_bases WHERE id=$1`, id)
		return nil, err
	}
	r.audit(ctx, "base.create", "records_base", id)
	return r.GetBase(ctx, a, id)
}

// UpdateBase edits name, description, colour and org access (admin only).
func (r *Repository) UpdateBase(ctx context.Context, a knowkit.Actor, id string, in BaseInput) (*Base, error) {
	if _, err := r.getBase(ctx, a, id, RoleAdmin); err != nil {
		return nil, err
	}
	if err := cleanBase(&in); err != nil {
		return nil, err
	}
	if _, err := r.pool.Exec(ctx, `UPDATE adrient.records_bases SET name=$3, description=$4, color=$5, org_access=$6, updated_at=now() WHERE org_id=$1 AND id=$2`,
		a.Org, id, in.Name, strings.TrimSpace(in.Description), in.Color, in.OrgAccess); err != nil {
		return nil, err
	}
	r.audit(ctx, "base.update", "records_base", id)
	return r.GetBase(ctx, a, id)
}

// TrashBase moves a base to the trash; RestoreBase brings it back; DeleteBase removes it for good.
func (r *Repository) TrashBase(ctx context.Context, a knowkit.Actor, id string, trash bool) error {
	b, err := r.getBase(ctx, a, id, RoleAdmin)
	if err != nil {
		return err
	}
	if !trash && b.TrashedAt == nil {
		return nil
	}
	if trash {
		_, err = r.pool.Exec(ctx, `UPDATE adrient.records_bases SET trashed_at=now() WHERE org_id=$1 AND id=$2`, a.Org, id)
	} else {
		_, err = r.pool.Exec(ctx, `UPDATE adrient.records_bases SET trashed_at=NULL WHERE org_id=$1 AND id=$2`, a.Org, id)
	}
	r.audit(ctx, map[bool]string{true: "base.trash", false: "base.restore"}[trash], "records_base", id)
	return err
}

// DeleteBase deletes a trashed base permanently.
func (r *Repository) DeleteBase(ctx context.Context, a knowkit.Actor, id string) error {
	b, err := r.getBase(ctx, a, id, RoleAdmin)
	if err != nil {
		return err
	}
	if b.TrashedAt == nil {
		return knowkit.Invalid("move the base to the trash first")
	}
	_, err = r.pool.Exec(ctx, `DELETE FROM adrient.records_bases WHERE org_id=$1 AND id=$2`, a.Org, id)
	r.audit(ctx, "base.delete", "records_base", id)
	return err
}

// SetMembers replaces the people a base is shared with.
func (r *Repository) SetMembers(ctx context.Context, a knowkit.Actor, id string, members []Member) error {
	b, err := r.getBase(ctx, a, id, RoleAdmin)
	if err != nil {
		return err
	}
	if len(members) > 500 {
		return knowkit.Invalid("too many members")
	}
	tx, err := r.pool.Begin(ctx)
	if err != nil {
		return err
	}
	defer tx.Rollback(ctx) //nolint:errcheck
	if _, err := tx.Exec(ctx, `DELETE FROM adrient.records_base_members WHERE base_id=$1`, id); err != nil {
		return err
	}
	for _, m := range members {
		if !knowkit.IsUUID(m.UserID) || !knowkit.OneOf(m.Role, "viewer", "editor", "admin") || m.UserID == b.OwnerID {
			continue
		}
		if _, err := tx.Exec(ctx, `INSERT INTO adrient.records_base_members (base_id, org_id, user_id, role)
			SELECT $1,$2,u.id,$4 FROM adrient.users u WHERE u.id=$3 AND u.org_id=$2 ON CONFLICT (base_id,user_id) DO UPDATE SET role=EXCLUDED.role`,
			id, a.Org, m.UserID, m.Role); err != nil {
			return err
		}
	}
	r.audit(ctx, "base.share", "records_base", id)
	return tx.Commit(ctx)
}

// GetBase returns a base with its tables, fields, views, counts and members.
func (r *Repository) GetBase(ctx context.Context, a knowkit.Actor, id string) (*Base, error) {
	b, err := r.getBase(ctx, a, id, RoleView)
	if err != nil {
		return nil, err
	}
	s, err := loadSchema(ctx, r.pool, a.Org, id)
	if err != nil {
		return nil, err
	}
	counts := map[string]int64{}
	rows, err := r.pool.Query(ctx, `SELECT t.id::text, count(r.id) FROM adrient.records_tables t LEFT JOIN adrient.records_records r ON r.table_id=t.id WHERE t.org_id=$1 AND t.base_id=$2 GROUP BY t.id`, a.Org, id)
	if err != nil {
		return nil, err
	}
	for rows.Next() {
		var tid string
		var n int64
		if err := rows.Scan(&tid, &n); err != nil {
			rows.Close()
			return nil, err
		}
		counts[tid] = n
	}
	rows.Close()
	views := map[string][]View{}
	vrows, err := r.pool.Query(ctx, `SELECT v.id::text, v.table_id::text, v.name, v.type, v.config, v.position FROM adrient.records_views v JOIN adrient.records_tables t ON t.id=v.table_id WHERE t.org_id=$1 AND t.base_id=$2 ORDER BY v.position, v.created_at`, a.Org, id)
	if err != nil {
		return nil, err
	}
	for vrows.Next() {
		var v View
		if err := vrows.Scan(&v.ID, &v.TableID, &v.Name, &v.Type, &v.Config, &v.Position); err != nil {
			vrows.Close()
			return nil, err
		}
		if v.Config == nil {
			v.Config = map[string]any{}
		}
		views[v.TableID] = append(views[v.TableID], v)
	}
	vrows.Close()
	for _, t := range s.tables {
		t.RecordCount = counts[t.ID]
		t.Views = views[t.ID]
		if t.Views == nil {
			t.Views = []View{}
		}
		t.Fields = []Field{}
		for _, f := range s.byTbl[t.ID] {
			t.Fields = append(t.Fields, apiField(f, s))
		}
		b.Tables = append(b.Tables, *t)
	}
	sort.Slice(b.Tables, func(i, j int) bool { return b.Tables[i].Position < b.Tables[j].Position })
	if b.Role == RoleAdmin {
		mrows, err := r.pool.Query(ctx, `SELECT m.user_id::text, COALESCE(NULLIF(u.display_name,''),u.email), m.role FROM adrient.records_base_members m JOIN adrient.users u ON u.id=m.user_id WHERE m.base_id=$1 ORDER BY 2`, id)
		if err != nil {
			return nil, err
		}
		for mrows.Next() {
			var m Member
			if err := mrows.Scan(&m.UserID, &m.Name, &m.Role); err != nil {
				mrows.Close()
				return nil, err
			}
			b.Members = append(b.Members, m)
		}
		mrows.Close()
	}
	return b, nil
}


// CreateTable adds a table with a primary text field and a grid view.
func (r *Repository) CreateTable(ctx context.Context, a knowkit.Actor, baseID, name string) (*Table, error) {
	if _, err := r.getBase(ctx, a, baseID, RoleEdit); err != nil {
		return nil, err
	}
	name = strings.TrimSpace(name)
	if name == "" || utf8.RuneCountInString(name) > 120 {
		return nil, knowkit.Invalid("a table needs a name of up to 120 characters")
	}
	var n int
	_ = r.pool.QueryRow(ctx, `SELECT count(*) FROM adrient.records_tables WHERE base_id=$1`, baseID).Scan(&n)
	if n >= MaxTablesPerBase {
		return nil, knowkit.Invalid("a base can have at most %d tables", MaxTablesPerBase)
	}
	tx, err := r.pool.Begin(ctx)
	if err != nil {
		return nil, err
	}
	defer tx.Rollback(ctx) //nolint:errcheck
	t := &Table{BaseID: baseID, Name: name, Position: n}
	if err := tx.QueryRow(ctx, `INSERT INTO adrient.records_tables (org_id, base_id, name, position) VALUES ($1,$2,$3,$4) RETURNING id::text`, a.Org, baseID, name, n).Scan(&t.ID); err != nil {
		return nil, err
	}
	if _, err := tx.Exec(ctx, `INSERT INTO adrient.records_fields (org_id, base_id, table_id, name, type, position) VALUES ($1,$2,$3,'Name','text',0)`, a.Org, baseID, t.ID); err != nil {
		return nil, err
	}
	if _, err := tx.Exec(ctx, `INSERT INTO adrient.records_views (org_id, table_id, name, type, position, created_by) VALUES ($1,$2,'Grid view','grid',0,$3)`, a.Org, t.ID, a.User); err != nil {
		return nil, err
	}
	if err := tx.Commit(ctx); err != nil {
		return nil, err
	}
	r.audit(ctx, "table.create", "records_table", t.ID)
	return t, nil
}

// UpdateTable renames a table or moves it (position).
func (r *Repository) UpdateTable(ctx context.Context, a knowkit.Actor, tableID, name, description string, position *int) error {
	b, err := r.tableBase(ctx, a, tableID, RoleEdit)
	if err != nil {
		return err
	}
	name = strings.TrimSpace(name)
	if name == "" || utf8.RuneCountInString(name) > 120 {
		return knowkit.Invalid("a table needs a name of up to 120 characters")
	}
	if _, err := r.pool.Exec(ctx, `UPDATE adrient.records_tables SET name=$3, description=$4 WHERE org_id=$1 AND id=$2`, a.Org, tableID, name, description); err != nil {
		return err
	}
	if position != nil {
		// Renumber so positions stay dense and the table lands where asked.
		rows, err := r.pool.Query(ctx, `SELECT id::text FROM adrient.records_tables WHERE base_id=$1 AND id<>$2 ORDER BY position, created_at`, b.ID, tableID)
		if err != nil {
			return err
		}
		var ids []string
		for rows.Next() {
			var id string
			_ = rows.Scan(&id)
			ids = append(ids, id)
		}
		rows.Close()
		p := *position
		if p < 0 {
			p = 0
		}
		if p > len(ids) {
			p = len(ids)
		}
		ids = append(ids[:p], append([]string{tableID}, ids[p:]...)...)
		for i, id := range ids {
			if _, err := r.pool.Exec(ctx, `UPDATE adrient.records_tables SET position=$2 WHERE id=$1`, id, i); err != nil {
				return err
			}
		}
	}
	return nil
}

// DeleteTable removes a table and everything in it. Links from other tables to it go too.
func (r *Repository) DeleteTable(ctx context.Context, a knowkit.Actor, tableID string) error {
	b, err := r.tableBase(ctx, a, tableID, RoleEdit)
	if err != nil {
		return err
	}
	var n int
	_ = r.pool.QueryRow(ctx, `SELECT count(*) FROM adrient.records_tables WHERE base_id=$1`, b.ID).Scan(&n)
	if n <= 1 {
		return knowkit.Invalid("a base needs at least one table")
	}
	tx, err := r.pool.Begin(ctx)
	if err != nil {
		return err
	}
	defer tx.Rollback(ctx) //nolint:errcheck
	// Fields in other tables that point here (links, and the lookups and rollups through them) go as well.
	if _, err := tx.Exec(ctx, `DELETE FROM adrient.records_fields WHERE base_id=$1 AND table_id<>$2 AND (
		(type='link' AND options->>'table_id'=$2::text)
		OR (type IN ('lookup','rollup','count') AND options->>'link_field_id' IN (SELECT id::text FROM adrient.records_fields WHERE base_id=$1 AND type='link' AND options->>'table_id'=$2::text)))`, b.ID, tableID); err != nil {
		return err
	}
	if _, err := tx.Exec(ctx, `DELETE FROM adrient.records_tables WHERE org_id=$1 AND id=$2`, a.Org, tableID); err != nil {
		return err
	}
	r.audit(ctx, "table.delete", "records_table", tableID)
	return tx.Commit(ctx)
}


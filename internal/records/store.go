// SaveView creates (id "") or edits a view.
func (r *Repository) SaveView(ctx context.Context, a knowkit.Actor, tableID, id string, v View) (*View, error) {
	if _, err := r.tableBase(ctx, a, tableID, RoleEdit); err != nil {
		return nil, err
	}
	v.Name = strings.TrimSpace(v.Name)
	if v.Name == "" || utf8.RuneCountInString(v.Name) > 120 {
		return nil, knowkit.Invalid("a view needs a name of up to 120 characters")
	}
	if !knowkit.OneOf(v.Type, "grid", "kanban", "gallery", "calendar", "list", "form") {
		return nil, knowkit.Invalid("view type must be grid, kanban, gallery, calendar, list or form")
	}
	if v.Config == nil {
		v.Config = map[string]any{}
	}
	raw, _ := json.Marshal(v.Config)
	if len(raw) > 64<<10 {
		return nil, knowkit.Invalid("the view settings are too large")
	}
	v.TableID = tableID
	if id == "" {
		err := r.pool.QueryRow(ctx, `INSERT INTO adrient.records_views (org_id, table_id, name, type, config, position, created_by)
			VALUES ($1,$2,$3,$4,$5,(SELECT COALESCE(max(position)+1,0) FROM adrient.records_views WHERE table_id=$2),$6) RETURNING id::text, position`,
			a.Org, tableID, v.Name, v.Type, raw, a.User).Scan(&v.ID, &v.Position)
		return &v, err
	}
	tag, err := r.pool.Exec(ctx, `UPDATE adrient.records_views SET name=$4, type=$5, config=$6 WHERE org_id=$1 AND table_id=$2 AND id=$3`, a.Org, tableID, id, v.Name, v.Type, raw)
	if err != nil {
		return nil, err
	}
	if tag.RowsAffected() == 0 {
		return nil, knowkit.ErrNotFound
	}
	v.ID = id
	return &v, nil
}

// DeleteView removes a view; a table keeps at least one.
func (r *Repository) DeleteView(ctx context.Context, a knowkit.Actor, tableID, id string) error {
	if _, err := r.tableBase(ctx, a, tableID, RoleEdit); err != nil {
		return err
	}
	var n int
	_ = r.pool.QueryRow(ctx, `SELECT count(*) FROM adrient.records_views WHERE table_id=$1`, tableID).Scan(&n)
	if n <= 1 {
		return knowkit.Invalid("a table needs at least one view")
	}
	_, err := r.pool.Exec(ctx, `DELETE FROM adrient.records_views WHERE org_id=$1 AND table_id=$2 AND id=$3`, a.Org, tableID, id)
	return err
}

// CreateEmbedded makes a base owned by another module (source "wiki"), with one table.
// Access to it is decided by that module through Deps.ExternalRole. taskBoard adds Status and Due fields.
func (r *Repository) CreateEmbedded(ctx context.Context, a knowkit.Actor, name, source, ref string, taskBoard bool) (baseID, tableID string, err error) {
	if name == "" {
		name = "Untitled database"
	}
	if err = r.pool.QueryRow(ctx, `INSERT INTO adrient.records_bases (org_id, name, owner_id, source, source_ref) VALUES ($1,$2,$3,$4,$5) RETURNING id::text`,
		a.Org, name, a.User, source, ref).Scan(&baseID); err != nil {
		return
	}
	var t *Table
	if t, err = r.createTableNoAuth(ctx, a, baseID, "Rows"); err != nil {
		return
	}
	tableID = t.ID
	if taskBoard {
		st, e := r.insertField(ctx, a, baseID, tableID, Field{Name: "Status", Type: TSelect, Options: map[string]any{"choices": normaliseChoices([]any{"To do", "In progress", "Done"})}}, 1)
		if e != nil {
			return "", "", e
		}
		if _, e = r.insertField(ctx, a, baseID, tableID, Field{Name: "Due", Type: TDate, Options: map[string]any{}}, 2); e != nil {
			return "", "", e
		}
		_, _ = r.pool.Exec(ctx, `INSERT INTO adrient.records_views (org_id, table_id, name, type, config, position, created_by) VALUES ($1,$2,'Board','kanban',$3,1,$4)`,
			a.Org, tableID, []byte(`{"stack_by":"`+st+`"}`), a.User)
	}
	return
}


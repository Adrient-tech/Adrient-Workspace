// FieldInput creates or edits a field.
type FieldInput struct {
	Name        string         `json:"name"`
	Type        string         `json:"type"`
	Description string         `json:"description"`
	Options     map[string]any `json:"options"`
	TwoWay      *bool          `json:"two_way"`
	Position    *int           `json:"position"`
}

// resolveFormulaNames turns {Field Name} into {id} so renames never break formulas.
func resolveFormulaNames(src string, s *schema, tableID string, self string) (string, error) {
	fm, err := ParseFormula(src)
	if err != nil {
		return "", knowkit.Invalid("formula: %v", err)
	}
	out := src
	for _, ref := range fm.Refs() {
		if knowkit.IsUUID(ref) {
			if f, ok := s.field(ref); ok && f.TableID == tableID {
				continue
			}
		}
		f, ok := s.fieldByName(tableID, ref)
		if !ok {
			return "", knowkit.Invalid("formula: there is no field named {%s}", ref)
		}
		if f.ID == self {
			return "", knowkit.Invalid("formula: a formula cannot use its own field")
		}
		out = strings.ReplaceAll(out, "{"+ref+"}", "{"+f.ID+"}")
	}
	return out, nil
}

// displayFormula turns {id} back into {Field Name}.
func displayFormula(src string, s *schema) string {
	fm, err := ParseFormula(src)
	if err != nil {
		return src
	}
	out := src
	for _, ref := range fm.Refs() {
		if f, ok := s.field(ref); ok {
			out = strings.ReplaceAll(out, "{"+ref+"}", "{"+f.Name+"}")
		}
	}
	return out
}

// formulaCycle reports whether making field `self` depend on its refs creates a loop.
func formulaCycle(s *schema, self string, srcFor map[string]string) bool {
	var visit func(id string, seen map[string]bool) bool
	visit = func(id string, seen map[string]bool) bool {
		if id == self && len(seen) > 0 {
			return true
		}
		if seen[id] {
			return false
		}
		seen[id] = true
		src := srcFor[id]
		if src == "" {
			f, ok := s.field(id)
			if !ok {
				return false
			}
			switch f.Type {
			case TFormula:
				src = f.optStr("formula")
			case TButton:
				src = f.optStr("url")
			}
		}
		if src == "" {
			return false
		}
		fm, err := ParseFormula(src)
		if err != nil {
			return false
		}
		for _, ref := range fm.Refs() {
			if ref == self || visit(ref, seen) {
				return true
			}
		}
		return false
	}
	return visit(self, map[string]bool{})
}

func (r *Repository) validateFieldRefs(s *schema, f *Field) error {
	switch f.Type {
	case TLookup, TRollup, TCount:
		lf, ok := s.field(f.optStr("link_field_id"))
		if !ok || lf.TableID != f.TableID || lf.Type != TLink {
			return knowkit.Invalid("choose a link field of this table")
		}
		if f.Type == TCount {
			return nil
		}
		_, _, tid := s.linkInfo(lf)
		tf, ok := s.field(f.optStr("target_field_id"))
		if !ok || tf.TableID != tid {
			return knowkit.Invalid("choose a field of the linked table")
		}
	case TFormula, TButton:
		key := "formula"
		if f.Type == TButton {
			key = "url"
		}
		src := f.optStr(key)
		if f.Type == TButton && src == "" {
			return nil
		}
		resolved, err := resolveFormulaNames(src, s, f.TableID, f.ID)
		if err != nil {
			return err
		}
		f.Options[key] = resolved
		if f.ID != "" && formulaCycle(s, f.ID, map[string]string{f.ID: resolved}) {
			return knowkit.Invalid("formula: circular reference")
		}
	}
	return nil
}

// CreateField adds a field. A link field also creates its reverse field unless two_way is false.
func (r *Repository) CreateField(ctx context.Context, a knowkit.Actor, tableID string, in FieldInput) (*Field, error) {
	b, err := r.tableBase(ctx, a, tableID, RoleEdit)
	if err != nil {
		return nil, err
	}
	s, err := loadSchema(ctx, r.pool, a.Org, b.ID)
	if err != nil {
		return nil, err
	}
	if len(s.byTbl[tableID]) >= MaxFieldsPerTable {
		return nil, knowkit.Invalid("a table can have at most %d fields", MaxFieldsPerTable)
	}
	f := Field{ID: NewID(), TableID: tableID, Name: strings.TrimSpace(in.Name), Type: in.Type, Description: in.Description, Options: in.Options}
	if f.Options == nil {
		f.Options = map[string]any{}
	}
	if f.Type == TSelect || f.Type == TMulti {
		f.Options["choices"] = normaliseChoices(f.Options["choices"])
	}
	if _, dup := s.fieldByName(tableID, f.Name); dup {
		return nil, knowkit.Invalid("this table already has a field named %q", f.Name)
	}
	if err := ValidateField(f); err != nil {
		return nil, err
	}
	s.fields[f.ID] = f // so formula checks can see it
	if err := r.validateFieldRefs(s, &f); err != nil {
		return nil, err
	}
	pos := len(s.byTbl[tableID])
	var rev *Field
	if f.Type == TLink {
		tid := f.optStr("table_id")
		if t := s.tables[tid]; t == nil {
			return nil, knowkit.Invalid("choose a table of this base to link to")
		}
		if _, ok := f.Options["allow_multiple"]; !ok {
			f.Options["allow_multiple"] = true
		}
		if in.TwoWay == nil || *in.TwoWay {
			name := s.tables[tableID].Name
			for i := 2; ; i++ {
				if _, dup := s.fieldByName(tid, name); !dup {
					break
				}
				name = fmt.Sprintf("%s %d", s.tables[tableID].Name, i)
			}
			rev = &Field{ID: NewID(), TableID: tid, Name: name, Type: TLink,
				Options: map[string]any{"table_id": tableID, "inverse_field_id": f.ID, "reverse": true, "allow_multiple": true}}
			f.Options["inverse_field_id"] = rev.ID
		}
	}
	tx, err := r.pool.Begin(ctx)
	if err != nil {
		return nil, err
	}
	defer tx.Rollback(ctx) //nolint:errcheck
	ins := func(x Field, position int) error {
		raw, _ := json.Marshal(x.Options)
		_, err := tx.Exec(ctx, `INSERT INTO adrient.records_fields (id, org_id, base_id, table_id, name, type, description, options, position) VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9)`,
			x.ID, a.Org, b.ID, x.TableID, x.Name, x.Type, x.Description, raw, position)
		return err
	}
	if err := ins(f, pos); err != nil {
		return nil, err
	}
	if rev != nil {
		if err := ins(*rev, len(s.byTbl[rev.TableID])); err != nil {
			return nil, err
		}
	}
	if err := tx.Commit(ctx); err != nil {
		return nil, err
	}
	f.Position = pos
	if f.Type == TFormula {
		f.Options["formula"] = displayFormula(f.optStr("formula"), s)
	}
	r.audit(ctx, "field.create", "records_field", f.ID)
	return &f, nil
}

func normaliseChoices(v any) []any {
	l, _ := v.([]any)
	out := make([]any, 0, len(l))
	colors := []string{"#2D7FF9", "#18BFFF", "#20D9D2", "#20C933", "#FFD66E", "#FF9F40", "#F82B60", "#FF08C2", "#8B46FF", "#666666"}
	for i, e := range l {
		m, ok := e.(map[string]any)
		if !ok {
			if s, isStr := e.(string); isStr {
				m = map[string]any{"name": s}
			} else {
				continue
			}
		}
		name, _ := m["name"].(string)
		id, _ := m["id"].(string)
		col, _ := m["color"].(string)
		if id == "" {
			id = "ch" + NewID()[:8]
		}
		if col == "" {
			col = colors[i%len(colors)]
		}
		out = append(out, map[string]any{"id": id, "name": strings.TrimSpace(name), "color": col})
	}
	return out
}

// UpdateField renames a field, edits its options or changes its type (values are converted).
func (r *Repository) UpdateField(ctx context.Context, a knowkit.Actor, fieldID string, in FieldInput) (*Field, int, error) {
	var tableID string
	if !knowkit.IsUUID(fieldID) {
		return nil, 0, knowkit.ErrNotFound
	}
	if err := r.pool.QueryRow(ctx, `SELECT table_id::text FROM adrient.records_fields WHERE org_id=$1 AND id=$2`, a.Org, fieldID).Scan(&tableID); err != nil {
		return nil, 0, knowkit.ErrNotFound
	}
	b, err := r.tableBase(ctx, a, tableID, RoleEdit)
	if err != nil {
		return nil, 0, err
	}
	s, err := loadSchema(ctx, r.pool, a.Org, b.ID)
	if err != nil {
		return nil, 0, err
	}
	old, _ := s.field(fieldID)
	nf := old
	if strings.TrimSpace(in.Name) != "" {
		nf.Name = strings.TrimSpace(in.Name)
	}
	nf.Description = in.Description
	if in.Type != "" {
		nf.Type = in.Type
	}
	if in.Options != nil {
		nf.Options = in.Options
	}
	if nf.Type == TSelect || nf.Type == TMulti {
		nf.Options["choices"] = normaliseChoices(nf.Options["choices"])
	}
	if other, dup := s.fieldByName(tableID, nf.Name); dup && other.ID != fieldID {
		return nil, 0, knowkit.Invalid("this table already has a field named %q", nf.Name)
	}
	primary, _ := s.primary(tableID)
	if fieldID == primary.ID && (IsComputed(nf.Type) && nf.Type != TFormula && nf.Type != TAutonumber || nf.Type == TLink || nf.Type == TAttachment) {
		return nil, 0, knowkit.Invalid("the first field must be text, a number, a formula or an autonumber")
	}
	if old.Type == TLink && nf.Type != TLink {
		return nil, 0, knowkit.Invalid("a link field cannot change type; delete it and add a new field")
	}
	if nf.Type == TLink && old.Type != TLink {
		return nil, 0, knowkit.Invalid("convert to a link field is not supported; add a link field and paste the names into it")
	}
	if err := ValidateField(nf); err != nil {
		return nil, 0, err
	}
	s.fields[nf.ID] = nf
	if err := r.validateFieldRefs(s, &nf); err != nil {
		return nil, 0, err
	}
	cleared := 0
	tx, err := r.pool.Begin(ctx)
	if err != nil {
		return nil, 0, err
	}
	defer tx.Rollback(ctx) //nolint:errcheck
	if old.Type != nf.Type && !(IsComputed(old.Type) && IsComputed(nf.Type)) {
		var cerr error
		nf, cleared, cerr = r.convertValues(ctx, tx, a, b.ID, old, nf)
		if cerr != nil {
			return nil, 0, cerr
		}
	}
	raw, _ := json.Marshal(nf.Options)
	if _, err := tx.Exec(ctx, `UPDATE adrient.records_fields SET name=$3, type=$4, description=$5, options=$6 WHERE org_id=$1 AND id=$2`, a.Org, fieldID, nf.Name, nf.Type, nf.Description, raw); err != nil {
		return nil, 0, err
	}
	if in.Position != nil {
		if _, err := tx.Exec(ctx, `UPDATE adrient.records_fields SET position=$2 WHERE id=$1`, fieldID, *in.Position); err != nil {
			return nil, 0, err
		}
	}
	// Removing a select option clears it from records.
	if (nf.Type == TSelect || nf.Type == TMulti) && old.Type == nf.Type {
		keep := map[string]bool{}
		for _, c := range nf.Choices() {
			keep[c.ID] = true
		}
		for _, c := range old.Choices() {
			if !keep[c.ID] {
				if nf.Type == TSelect {
					_, err = tx.Exec(ctx, `UPDATE adrient.records_records SET data = data - $2 WHERE table_id=$1 AND data->>$2 = $3`, tableID, fieldID, c.ID)
				} else {
					_, err = tx.Exec(ctx, `UPDATE adrient.records_records SET data = jsonb_set(data, ARRAY[$2], COALESCE((SELECT jsonb_agg(e) FROM jsonb_array_elements(data->$2) e WHERE e <> to_jsonb($3::text)),'[]'::jsonb))
						WHERE table_id=$1 AND data->$2 ? $3`, tableID, fieldID, c.ID)
				}
				if err != nil {
					return nil, 0, err
				}
			}
		}
	}
	if err := tx.Commit(ctx); err != nil {
		return nil, 0, err
	}
	if nf.Type == TFormula {
		nf.Options["formula"] = displayFormula(nf.optStr("formula"), s)
	}
	r.audit(ctx, "field.update", "records_field", fieldID)
	return &nf, cleared, nil
}

// convertValues rewrites stored values when a field changes type. A value that
// does not fit the new type is cleared and counted.
func (r *Repository) convertValues(ctx context.Context, tx pgx.Tx, a knowkit.Actor, baseID string, from, to Field) (Field, int, error) {
	rows, err := tx.Query(ctx, `SELECT id::text, data->$2 FROM adrient.records_records WHERE org_id=$1 AND table_id=$3 AND data ? $2`, a.Org, from.ID, from.TableID)
	if err != nil {
		return to, 0, err
	}
	type kv struct {
		id  string
		val any
	}
	var items []kv
	for rows.Next() {
		var id string
		var raw []byte
		if err := rows.Scan(&id, &raw); err != nil {
			rows.Close()
			return to, 0, err
		}
		var v any
		_ = json.Unmarshal(raw, &v)
		items = append(items, kv{id, v})
	}
	rows.Close()
	if IsComputed(to.Type) {
		_, err := tx.Exec(ctx, `UPDATE adrient.records_records SET data = data - $2 WHERE table_id=$1`, from.TableID, from.ID)
		return to, len(items), err
	}
	// Texts of every value, to collect select options up front.
	texts := make(map[string]string, len(items))
	for _, it := range items {
		texts[it.id] = Display(from, it.val, nil)
	}
	if to.Type == TSelect || to.Type == TMulti {
		have := to.Choices()
		known := map[string]bool{}
		for _, c := range have {
			known[strings.ToLower(c.Name)] = true
		}
		var add []any
		for _, c := range have {
			add = append(add, map[string]any{"id": c.ID, "name": c.Name, "color": c.Color})
		}
		var names []string
		for _, t := range texts {
			if to.Type == TMulti {
				names = append(names, splitList(t)...)
			} else if t != "" {
				names = append(names, t)
			}
		}
		sort.Strings(names)
		for _, n := range names {
			if !known[strings.ToLower(n)] && len(add) < 200 {
				known[strings.ToLower(n)] = true
				add = append(add, map[string]any{"name": n})
			}
		}
		to.Options["choices"] = normaliseChoices(add)
	}
	cleared := 0
	for _, it := range items {
		var nv any
		text := texts[it.id]
		if from.Type == TCheckbox && (to.Type == TNumber || to.Type == TRating) {
			text = map[bool]string{true: "1", false: ""}[it.val == true]
		}
		if from.Type == TPercent && (to.Type == TNumber) {
			text = fmtNum(toNum(it.val))
		}
		if from.Type == TDuration && to.Type == TNumber {
			text = fmtNum(toNum(it.val))
		}
		v, _, perr := ParseText(to, text)
		if perr != nil {
			cleared++
		}
		nv = v
		if nv == nil {
			if _, err := tx.Exec(ctx, `UPDATE adrient.records_records SET data = data - $2 WHERE id=$1`, it.id, from.ID); err != nil {
				return to, 0, err
			}
			continue
		}
		raw, _ := json.Marshal(nv)
		if _, err := tx.Exec(ctx, `UPDATE adrient.records_records SET data = jsonb_set(data, ARRAY[$2], $3::jsonb) WHERE id=$1`, it.id, from.ID, raw); err != nil {
			return to, 0, err
		}
	}
	return to, cleared, nil
}

// DeleteField removes a field (not the first one) and the fields that depend on it.
func (r *Repository) DeleteField(ctx context.Context, a knowkit.Actor, fieldID string) error {
	var tableID string
	if !knowkit.IsUUID(fieldID) {
		return knowkit.ErrNotFound
	}
	if err := r.pool.QueryRow(ctx, `SELECT table_id::text FROM adrient.records_fields WHERE org_id=$1 AND id=$2`, a.Org, fieldID).Scan(&tableID); err != nil {
		return knowkit.ErrNotFound
	}
	b, err := r.tableBase(ctx, a, tableID, RoleEdit)
	if err != nil {
		return err
	}
	s, err := loadSchema(ctx, r.pool, a.Org, b.ID)
	if err != nil {
		return err
	}
	f, _ := s.field(fieldID)
	if p, _ := s.primary(tableID); p.ID == fieldID {
		return knowkit.Invalid("the first field cannot be deleted; make another field first by moving it")
	}
	doomed := map[string]bool{fieldID: true}
	if f.Type == TLink {
		if inv := f.optStr("inverse_field_id"); inv != "" {
			doomed[inv] = true
		}
	}
	// Anything built on a doomed field goes too.
	for changed := true; changed; {
		changed = false
		for _, g := range s.fields {
			if doomed[g.ID] {
				continue
			}
			dep := false
			switch g.Type {
			case TLookup, TRollup, TCount:
				dep = doomed[g.optStr("link_field_id")] || doomed[g.optStr("target_field_id")]
			case TFormula, TButton:
				src := g.optStr("formula")
				if g.Type == TButton {
					src = g.optStr("url")
				}
				if fm, err := ParseFormula(src); err == nil {
					for _, ref := range fm.Refs() {
						dep = dep || doomed[ref]
					}
				}
			}
			if dep {
				doomed[g.ID] = true
				changed = true
			}
		}
	}
	tx, err := r.pool.Begin(ctx)
	if err != nil {
		return err
	}
	defer tx.Rollback(ctx) //nolint:errcheck
	for id := range doomed {
		g, _ := s.field(id)
		if _, err := tx.Exec(ctx, `DELETE FROM adrient.records_fields WHERE id=$1`, id); err != nil {
			return err
		}
		if _, err := tx.Exec(ctx, `UPDATE adrient.records_records SET data = data - $2 WHERE table_id=$1 AND data ? $2`, g.TableID, id); err != nil {
			return err
		}
	}
	// Views keep field ids in their config; drop the dead ones.
	vrows, err := tx.Query(ctx, `SELECT id::text, config FROM adrient.records_views WHERE table_id=$1`, tableID)
	if err != nil {
		return err
	}
	type vc struct {
		id  string
		cfg map[string]any
	}
	var vs []vc
	for vrows.Next() {
		var v vc
		if err := vrows.Scan(&v.id, &v.cfg); err != nil {
			vrows.Close()
			return err
		}
		vs = append(vs, v)
	}
	vrows.Close()
	for _, v := range vs {
		if scrubView(v.cfg, doomed) {
			raw, _ := json.Marshal(v.cfg)
			if _, err := tx.Exec(ctx, `UPDATE adrient.records_views SET config=$2 WHERE id=$1`, v.id, raw); err != nil {
				return err
			}
		}
	}
	r.audit(ctx, "field.delete", "records_field", fieldID)
	return tx.Commit(ctx)
}

// scrubView removes deleted field ids from a view config; it reports whether anything changed.
func scrubView(cfg map[string]any, dead map[string]bool) bool {
	changed := false
	for _, key := range []string{"hidden", "field_order", "group_by"} {
		if l, ok := cfg[key].([]any); ok {
			var keep []any
			for _, e := range l {
				if s, _ := e.(string); !dead[s] {
					keep = append(keep, e)
				}
			}
			if len(keep) != len(l) {
				cfg[key] = keep
				changed = true
			}
		}
	}
	if l, ok := cfg["sort"].([]any); ok {
		var keep []any
		for _, e := range l {
			m, _ := e.(map[string]any)
			if s, _ := m["field"].(string); !dead[s] {
				keep = append(keep, e)
			}
		}
		if len(keep) != len(l) {
			cfg["sort"] = keep
			changed = true
		}
	}
	for _, key := range []string{"stack_by", "date_field", "end_date_field", "cover_field", "color_field"} {
		if s, _ := cfg[key].(string); dead[s] {
			delete(cfg, key)
			changed = true
		}
	}
	if f, ok := cfg["filter"].(map[string]any); ok && scrubFilter(f, dead) {
		changed = true
	}
	return changed
}

func scrubFilter(n map[string]any, dead map[string]bool) bool {
	changed := false
	if l, ok := n["conds"].([]any); ok {
		var keep []any
		for _, e := range l {
			m, _ := e.(map[string]any)
			if s, _ := m["field"].(string); s != "" && dead[s] {
				changed = true
				continue
			}
			if scrubFilter(m, dead) {
				changed = true
			}
			keep = append(keep, e)
		}
		n["conds"] = keep
	}
	return changed
}

